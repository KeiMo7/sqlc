// generate runs the real sqlc generation pipeline against a fixture
// directory and returns the rendered files keyed by absolute path.
func generate(t *testing.T, dir string) map[string]string {
	t.Helper()
	var stderr bytes.Buffer
	output, err := cmd.Generate(context.Background(), dir, "", &cmd.Options{
		Env:    cmd.Env{},
		Stderr: &stderr,
	})
	if err != nil {
		t.Fatalf("sqlc generate failed for %s: %s", dir, stderr.String())
	}
	return output
}

// assertIdempotent runs the pipeline twice and asserts byte-for-byte
// identical output, using the structured idempotent report so a failure
// names the first mismatching file and line instead of a vague
// "results differ".
func assertIdempotent(t *testing.T, dir string) idempotent.Report {
	t.Helper()
	report, err := idempotent.Check(context.Background(), func(ctx context.Context) (map[string]string, error) {
		var stderr bytes.Buffer
		return cmd.Generate(ctx, dir, "", &cmd.Options{
			Env:    cmd.Env{},
			Stderr: &stderr,
		})
	})
	if err != nil {
		t.Fatalf("idempotent check failed to run for %s: %v", dir, err)
	}
	if !report.Stable() {
		t.Fatalf("%s: %s\n%s", dir, report.Summary(), report.Detail())
	}
	return *report
}

func fileHashes(output map[string]string) map[string][32]byte {
	hashes := make(map[string][32]byte, len(output))
	for name, contents := range output {
		hashes[name] = sha256.Sum256([]byte(contents))
	}
	return hashes
}

func sortedKeys(m map[string][32]byte) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// TestIdempotentSingleFile covers a fixture whose queries live in one query
// file. Two consecutive generations must produce the same three output files
// byte for byte.
func TestIdempotentSingleFile(t *testing.T) {
	t.Parallel()
	dir, err := filepath.Abs(filepath.Join("testdata", "idempotent", "single_file", "postgresql"))
	if err != nil {
		t.Fatal(err)
	}

	report := assertIdempotent(t, dir)

	first := generate(t, dir)
	if len(first) != 3 {
		t.Fatalf("expected 3 output files, got %d: %v", len(first), sortedKeys(fileHashes(first)))
	}

	// Every committed golden file must match the freshly generated bytes.
	for name, contents := range first {
		golden, err := os.ReadFile(name)
		if err != nil {
			t.Fatalf("missing golden %s: %v", name, err)
		}
		if string(golden) != contents {
			t.Errorf("%s: generated bytes differ from committed golden", name)
		}
	}

	if report.FileCount != len(first) {
		t.Errorf("summary file count = %d, want %d", report.FileCount, len(first))
	}
	if report.ChangedFiles != 0 || report.AddedLines != 0 || report.RemovedLines != 0 {
		t.Errorf("stable run reported differences: %s", report.Summary())
	}
}

// TestIdempotentMultiFile covers a fixture split across three query files.
// Both the set of files and their ordering across runs must be stable, in
// addition to each file's bytes.
func TestIdempotentMultiFile(t *testing.T) {
	t.Parallel()
	dir, err := filepath.Abs(filepath.Join("testdata", "idempotent", "multi_file", "postgresql"))
	if err != nil {
		t.Fatal(err)
	}

	report := assertIdempotent(t, dir)

	first := generate(t, dir)
	second := generate(t, dir)

	wantFiles := []string{"authors.sql.go", "books.sql.go", "db.go", "models.go", "reviews.sql.go"}
	gotBases := make([]string, 0, len(first))
	for name := range first {
		gotBases = append(gotBases, filepath.Base(name))
	}
	sort.Strings(gotBases)
	if fmt.Sprint(gotBases) != fmt.Sprint(wantFiles) {
		t.Errorf("output file set = %v, want %v", gotBases, wantFiles)
	}

	// File order stability: the same keys must be present in both runs and
	// their hashes must agree.
	firstHashes, secondHashes := fileHashes(first), fileHashes(second)
	for _, name := range sortedKeys(firstHashes) {
		if _, ok := secondHashes[name]; !ok {
			t.Errorf("%s present in first run but missing from second", name)
			continue
		}
		if firstHashes[name] != secondHashes[name] {
			t.Errorf("%s: content hash changed between runs", name)
		}
	}
	if len(firstHashes) != len(secondHashes) {
		t.Errorf("file count changed: %d vs %d", len(firstHashes), len(secondHashes))
	}

	if report.FileCount != len(wantFiles) {
		t.Errorf("summary file count = %d, want %d", report.FileCount, len(wantFiles))
	}
}

// TestIdempotentIncremental copies the multi-file fixture into a temp
// directory, changes one query file, and asserts every other output file's
// hash is untouched while the file backing the changed query is the only one
// that moves.
func TestIdempotentIncremental(t *testing.T) {
	t.Parallel()

	src, err := filepath.Abs(filepath.Join("testdata", "idempotent", "multi_file", "postgresql"))
	if err != nil {
		t.Fatal(err)
	}

	dir := t.TempDir()
	for _, name := range []string{"sqlc.json", "schema.sql", "authors.sql", "books.sql", "reviews.sql"} {
		blob, err := os.ReadFile(filepath.Join(src, name))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, name), blob, 0644); err != nil {
			t.Fatal(err)
		}
	}

	before := generate(t, dir)
	beforeHashes := fileHashes(before)

	// Change exactly one query in books.sql.
	booksPath := filepath.Join(dir, "books.sql")
	books, err := os.ReadFile(booksPath)
	if err != nil {
		t.Fatal(err)
	}
	books = append(books, []byte("\n-- name: CountBooks :one\nSELECT count(*) FROM books;\n")...)
	if err := os.WriteFile(booksPath, books, 0644); err != nil {
		t.Fatal(err)
	}

	after := generate(t, dir)
	afterHashes := fileHashes(after)

	var changed []string
	for name, hash := range beforeHashes {
		next, ok := afterHashes[name]
		if !ok {
			t.Errorf("%s disappeared after an incremental change", name)
			continue
		}
		if next != hash {
			changed = append(changed, filepath.Base(name))
		}
	}
	sort.Strings(changed)

	if len(changed) != 1 || changed[0] != "books.sql.go" {
		t.Fatalf("incremental change touched %v, want only [books.sql.go]", changed)
	}

	// Explicit, named assertions for the files that must not move.
	for _, keep := range []string{"authors.sql.go", "db.go", "models.go", "reviews.sql.go"} {
		var beforeHash, afterHash [32]byte
		var found bool
		for name, hash := range beforeHashes {
			if filepath.Base(name) == keep {
				beforeHash, found = hash, true
			}
		}
		for name, hash := range afterHashes {
			if filepath.Base(name) == keep {
				afterHash = hash
			}
		}
		if !found {
			t.Fatalf("expected %s in the first generation", keep)
		}
		if beforeHash != afterHash {
			t.Errorf("%s hash changed after editing books.sql", keep)
		}
	}

	// Regenerating again from the mutated inputs must still be idempotent.
	assertIdempotent(t, dir)
}

// TestIdempotentReportDrilldown feeds the comparator a deliberately
// mismatching pair to prove the summary and the per-file detail report
// distinct, structured information and the first mismatch is pinpointed.
func TestIdempotentReportDrilldown(t *testing.T) {
	t.Parallel()

	first := map[string]string{
		"/out/a.go": "package out\n\ntype A struct{}\n",
		"/out/b.go": "package out\n\ntype B struct{}\n",
	}
	second := map[string]string{
		"/out/a.go": "package out\n\ntype A struct{ X int }\n",
		"/out/b.go": "package out\n\ntype B struct{}\n",
	}

	report := idempotent.Compare(first, second)
	if report.Stable() {
		t.Fatal("expected a mismatch report, got stable")
	}
	if report.FileCount != 2 {
		t.Errorf("FileCount = %d, want 2", report.FileCount)
	}
	if report.ChangedFiles != 1 {
		t.Errorf("ChangedFiles = %d, want 1", report.ChangedFiles)
	}
	if report.FirstMismatch == nil || report.FirstMismatch.File != "/out/a.go" {
		t.Fatalf("first mismatch = %+v, want /out/a.go", report.FirstMismatch)
	}
	if report.FirstMismatch.Diff == nil || report.FirstMismatch.Diff.Line != 3 {
		t.Fatalf("first mismatch line = %+v, want line 3", report.FirstMismatch.Diff)
	}
	if len(report.FileDiffs) != 1 || report.FileDiffs[0].Name != "/out/a.go" {
		t.Fatalf("file drilldown = %+v, want only /out/a.go", report.FileDiffs)
	}

	summary := report.Summary()
	detail := report.Detail()
	if summary == "" || detail == "" {
		t.Fatal("summary and detail must both be populated")
	}
	if !bytes.Contains([]byte(summary), []byte("not idempotent")) {
		t.Errorf("summary does not flag the mismatch: %q", summary)
	}
	if !bytes.Contains([]byte(detail), []byte("/out/a.go")) {
		t.Errorf("detail does not name the changed file: %q", detail)
	}
}

// TestIdempotentSourcesRegistered ensures every nondeterminism source the
// report names points at a real, stabilized site: the register must not rot
// into placeholder entries.
func TestIdempotentSourcesRegistered(t *testing.T) {
	t.Parallel()

	dir, err := filepath.Abs(filepath.Join("testdata", "idempotent", "multi_file", "postgresql"))
	if err != nil {
		t.Fatal(err)
	}
	report := assertIdempotent(t, dir)
	if len(report.Sources) == 0 {
		t.Fatal("expected registered nondeterminism sources")
	}
	for _, source := range report.Sources {
		if source.File == "" || source.Line <= 0 || source.Code == "" || source.Reason == "" {
			t.Errorf("incomplete source entry: %+v", source)
		}
		if source.Status != "sorted" && source.Status != "fallback" {
			t.Errorf("source %s has unknown status %q", source.File, source.Status)
		}
		// source.File is repo-root relative; the test runs from internal/endtoend.
		repoRoot, err := filepath.Abs(filepath.Join("..", ".."))
		if err != nil {
			t.Fatal(err)
		}
		if _, err := os.Stat(filepath.Join(repoRoot, source.File)); err != nil {
			t.Errorf("registered source file %s does not exist: %v", source.File, err)
		}
	}
}
